/**
 * The categories the app has shipped with since SCRUM-45. They are no longer the whole list: SCRUM-65
 * moved the catalogue into `public.facility_categories`, so an organization may append its own. This
 * constant survives for three reasons — it seeds that table, it labels a facility written before the
 * table existed, and the facilities screen falls back to it when the catalogue cannot be read.
 */
export const FACILITY_CATEGORIES = [
  "KITCHEN",
  "COLD_STORAGE",
  "FURNITURE",
  "ELECTRICAL",
  "CLEANING",
  "OTHER",
] as const;

export type BuiltInFacilityCategory = (typeof FACILITY_CATEGORIES)[number];

/** Codes are generated by `facilityCategoryCode()`; the database CHECKs the same shape (SCRUM-65). */
export const FACILITY_CATEGORY_CODE_PATTERN = /^[A-Z0-9_]{1,60}$/;

export const MAX_FACILITY_CATEGORY_CODE_LENGTH = 60;
export const MAX_FACILITY_CATEGORY_NAME_LENGTH = 60;

/**
 * The asset tag (SCRUM-67): `{số chi nhánh}{viết tắt chi nhánh}-{số thứ tự}`, e.g. `01HSVH-0001`. The
 * number comes from `branches.asset_prefix`, the letters from `branchAssetAcronym()` and the last part is
 * the next free number of that token inside the organization, which is what makes `(organization_id, code)`
 * unique.
 *
 * The branch number is optional in the pattern on purpose: a branch that has none yet (created before
 * SCRUM-67, or inserted by hand in the dashboard) falls back to the bare acronym, which produces
 * `HSVH-0001` — the SCRUM-66 shape. `facilities_code_check` (SCRUM-67) repeats this very pattern.
 *
 * The field is not editable any more, so the database can hold new rows to it — as `not valid`, which
 * leaves the rows written before it alone: a `DA_LAT-0001` from the first shape or a serial typed by hand
 * keeps working until the next edit re-tags it.
 */
export const FACILITY_ASSET_CODE_PATTERN = /^[0-9]*[A-Z0-9]{1,6}-[0-9]{4,}$/;

/** Longest branch acronym; a longer name is trimmed to this many initials by `branchAssetAcronym()`. */
export const MAX_FACILITY_ASSET_ACRONYM_LENGTH = 6;

/** Zero padding of `branches.asset_prefix`: `01HSVH-0001`. A branch past 99 keeps growing (`100HSVH`). */
export const BRANCH_ASSET_PREFIX_WIDTH = 2;

/** Zero padding of the running number: `01HSVH-0001`. A branch past `9999` keeps growing (`10000`). */
export const FACILITY_ASSET_SEQUENCE_WIDTH = 4;

/**
 * One row of `facility_categories` (SCRUM-65): the per-organization "Nhóm thiết bị" catalogue, which the
 * facilities tab may extend.
 *
 * `code` is what `Facility.category` stores — an uppercase token an operator never sees — and `name` is
 * what the screen shows: "Khu pha chế", or whatever the owner typed for a group of their own.
 */
export interface FacilityCategory {
  id: string;
  organization_id: string;
  code: string;
  name: string;
  created_at: string;
}

export interface CreateFacilityCategoryInput {
  /** The label the operator typed; unique inside the organization. */
  name: string;
  /** The code derived from that label (`facilityCategoryCode()`) and stored in `facilities.category`. */
  code: string;
}

/**
 * `MAINTENANCE` means "đang sửa chữa" and `BROKEN` means "hỏng, chờ xử lý" — both are the
 * states the maintenance workflow (SCRUM-46) acts on, so they are stored separately even
 * though the screens group them together.
 */
export const FACILITY_CONDITIONS = [
  "GOOD",
  "FAIR",
  "MAINTENANCE",
  "BROKEN",
] as const;

export type FacilityCondition = (typeof FACILITY_CONDITIONS)[number];

export interface Facility {
  id: string;
  branch_id: string;
  name: string;
  /**
   * The asset tag, always generated (SCRUM-67): `{số chi nhánh}{viết tắt}-{số}`, e.g. `01HSVH-0001`.
   * `null` only on a row written before the generator existed; the next edit gives it a code.
   */
  code: string | null;
  /** A `code` from the organization's `facility_categories` (SCRUM-65), enforced by a foreign key. */
  category: string;
  quantity: number;
  condition: FacilityCondition;
  last_checked_at: string | null;
  note: string | null;
  created_at: string;
  updated_at: string;
}

export interface CreateFacilityInput {
  branchId: string;
  name: string;
  category: string;
  quantity: number;
  condition: FacilityCondition;
  lastCheckedAt: string | null;
  note: string | null;
}

/**
 * The same fields with the same rules: the asset code is not part of a write any more (SCRUM-67) — the
 * create path always generates one and the update path generates one whenever the stored value would not
 * survive, so the body cannot carry a code at all.
 */
export type UpdateFacilityInput = CreateFacilityInput;

/**
 * What the repository persists (SCRUM-67): the write input plus the tag the use case decided on. The code
 * is deliberately absent from `CreateFacilityInput` — a request may not carry one — so this is the type
 * that crosses from a use case into persistence.
 */
export type FacilityRecordInput = CreateFacilityInput & {
  code: string;
};
