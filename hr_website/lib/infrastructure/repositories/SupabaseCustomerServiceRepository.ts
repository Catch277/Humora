import type { MaintenanceSummary } from "@/lib/domain/entities/MaintenanceSummary";
import type {
  CreateMaintenanceVisitInput,
  MaintenanceVisit,
  MaintenanceVisitFilters,
  MaintenanceVisitKind,
  UpdateMaintenanceVisitInput,
} from "@/lib/domain/entities/MaintenanceVisit";
import type {
  CustomerService,
  CustomerServiceFilters,
  CustomerServiceInput,
  CustomerServiceStatus,
  MaintenanceState,
  ServiceOverview,
  UpdateCustomerServiceInput,
  WarrantyState,
} from "@/lib/domain/entities/CustomerService";
import { CrmNotFoundError } from "@/lib/domain/errors/CrmNotFoundError";
import type { ICustomerServiceRepository } from "@/lib/domain/repositories/ICustomerServiceRepository";
import { throwCrmError } from "@/lib/infrastructure/repositories/crmErrors";
import { createSupabaseServerClient } from "@/lib/infrastructure/supabaseClient";

/** `warranty_end_on` is generated by the database (SCRUM-102) and is only ever read. */
const SERVICE_COLUMNS =
  "id, organization_id, customer_id, contract_id, service_name, serial_no, warranty_start_on, warranty_months, warranty_end_on, maintenance_interval_months, status, note, created_at, updated_at";

const VISIT_COLUMNS =
  "id, organization_id, service_id, customer_id, scheduled_on, completed_on, kind, technician, cost, summary, created_at, updated_at";

type Numeric = number | string;

type ServiceRow = {
  id: string;
  organization_id: string;
  customer_id: string;
  contract_id: string | null;
  service_name: string;
  serial_no: string | null;
  warranty_start_on: string;
  warranty_months: Numeric;
  warranty_end_on: string;
  maintenance_interval_months: Numeric;
  status: string;
  note: string | null;
  created_at: string;
  updated_at: string;
};

type ServiceOverviewRow = ServiceRow & {
  customer_name: string;
  app_name: string;
  contact_email: string;
  contract_no: string | null;
  last_completed_on: string | null;
  next_due_on: string | null;
  next_planned_on: string | null;
  warranty_state: string;
  maintenance_state: string;
};

type VisitRow = {
  id: string;
  organization_id: string;
  service_id: string;
  customer_id: string;
  scheduled_on: string;
  completed_on: string | null;
  kind: string;
  technician: string | null;
  cost: Numeric;
  summary: string | null;
  created_at: string;
  updated_at: string;
};

type SummaryRow = Partial<Record<keyof MaintenanceSummary, Numeric>>;

function toService(row: ServiceRow): CustomerService {
  return {
    id: row.id,
    organization_id: row.organization_id,
    customer_id: row.customer_id,
    contract_id: row.contract_id,
    service_name: row.service_name,
    serial_no: row.serial_no,
    warranty_start_on: row.warranty_start_on,
    warranty_months: Number(row.warranty_months),
    warranty_end_on: row.warranty_end_on,
    maintenance_interval_months: Number(row.maintenance_interval_months),
    status: row.status as CustomerServiceStatus,
    note: row.note,
    created_at: row.created_at,
    updated_at: row.updated_at,
  };
}

function toOverview(row: ServiceOverviewRow): ServiceOverview {
  return {
    ...toService(row),
    customer_name: row.customer_name,
    app_name: row.app_name,
    contact_email: row.contact_email,
    contract_no: row.contract_no,
    last_completed_on: row.last_completed_on,
    next_due_on: row.next_due_on,
    next_planned_on: row.next_planned_on,
    warranty_state: row.warranty_state as WarrantyState,
    maintenance_state: row.maintenance_state as MaintenanceState,
  };
}

function toVisit(row: VisitRow): MaintenanceVisit {
  return {
    id: row.id,
    organization_id: row.organization_id,
    service_id: row.service_id,
    customer_id: row.customer_id,
    scheduled_on: row.scheduled_on,
    completed_on: row.completed_on,
    kind: row.kind as MaintenanceVisitKind,
    technician: row.technician,
    cost: Number(row.cost),
    summary: row.summary,
    created_at: row.created_at,
    updated_at: row.updated_at,
  };
}

function servicePayload(input: CustomerServiceInput) {
  return {
    customer_id: input.customerId,
    contract_id: input.contractId,
    service_name: input.serviceName.trim(),
    serial_no: input.serialNo,
    warranty_start_on: input.warrantyStartOn,
    warranty_months: input.warrantyMonths,
    maintenance_interval_months: input.maintenanceIntervalMonths,
    status: input.status,
    note: input.note,
  };
}

/**
 * Supabase implementation of warranty, maintenance visits and their KPI (SCRUM-102).
 *
 * Like the contract repository, the derived values come from an RPC: `get_maintenance_overview` is the one
 * place that turns "the last completed visit plus the interval" into `next_due_on`, so a chip, the KPI strip
 * and the reminder queue read the same date. A visit's own state is derived by the entity helper.
 */
export class SupabaseCustomerServiceRepository
  implements ICustomerServiceRepository
{
  async overview(filters: CustomerServiceFilters): Promise<ServiceOverview[]> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase.rpc("get_maintenance_overview", {
      p_state: filters.state ?? null,
      p_customer_id: filters.customerId ?? null,
    });

    if (error) {
      throwCrmError(error, "load the services");
    }

    return ((data ?? []) as ServiceOverviewRow[]).map(toOverview);
  }

  async findById(id: string): Promise<CustomerService | null> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase
      .from("customer_services")
      .select(SERVICE_COLUMNS)
      .eq("id", id)
      .maybeSingle();

    if (error) {
      throwCrmError(error, "load the service");
    }

    return data ? toService(data as ServiceRow) : null;
  }

  async create(input: CustomerServiceInput): Promise<CustomerService> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase
      .from("customer_services")
      .insert(servicePayload(input))
      .select(SERVICE_COLUMNS)
      .single();

    if (error) {
      throwCrmError(error, "create the service");
    }

    return toService(data as ServiceRow);
  }

  async update(input: UpdateCustomerServiceInput): Promise<CustomerService> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase
      .from("customer_services")
      .update(servicePayload(input))
      .eq("id", input.id)
      .select(SERVICE_COLUMNS)
      .maybeSingle();

    if (error) {
      throwCrmError(error, "update the service");
    }

    if (!data) {
      throw new CrmNotFoundError(
        "Không tìm thấy dịch vụ này trong tổ chức của bạn.",
      );
    }

    return toService(data as ServiceRow);
  }

  async remove(id: string): Promise<void> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase
      .from("customer_services")
      .delete()
      .eq("id", id)
      .select("id")
      .maybeSingle();

    if (error) {
      throwCrmError(error, "delete the service");
    }

    if (!data) {
      throw new CrmNotFoundError(
        "Không tìm thấy dịch vụ này trong tổ chức của bạn.",
      );
    }
  }

  async summary(): Promise<MaintenanceSummary> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase.rpc("get_maintenance_summary");

    if (error) {
      throwCrmError(error, "load the maintenance summary");
    }

    const row = (data ?? {}) as SummaryRow;

    return {
      services_total: Number(row.services_total ?? 0),
      services_active: Number(row.services_active ?? 0),
      in_warranty: Number(row.in_warranty ?? 0),
      warranty_expired: Number(row.warranty_expired ?? 0),
      due_soon: Number(row.due_soon ?? 0),
      overdue: Number(row.overdue ?? 0),
      planned_visits: Number(row.planned_visits ?? 0),
      overdue_visits: Number(row.overdue_visits ?? 0),
    };
  }

  async visits(filters: MaintenanceVisitFilters): Promise<MaintenanceVisit[]> {
    const supabase = await createSupabaseServerClient();
    let query = supabase
      .from("customer_maintenance_visits")
      .select(VISIT_COLUMNS)
      .order("scheduled_on", { ascending: false })
      .order("created_at", { ascending: false });

    if (filters.serviceId) {
      query = query.eq("service_id", filters.serviceId);
    }

    if (filters.customerId) {
      query = query.eq("customer_id", filters.customerId);
    }

    const { data, error } = await query;

    if (error) {
      throwCrmError(error, "load the maintenance visits");
    }

    return ((data ?? []) as VisitRow[]).map(toVisit);
  }

  async findVisitById(id: string): Promise<MaintenanceVisit | null> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase
      .from("customer_maintenance_visits")
      .select(VISIT_COLUMNS)
      .eq("id", id)
      .maybeSingle();

    if (error) {
      throwCrmError(error, "load the maintenance visit");
    }

    return data ? toVisit(data as VisitRow) : null;
  }

  async createVisit(
    input: CreateMaintenanceVisitInput,
  ): Promise<MaintenanceVisit> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase
      .from("customer_maintenance_visits")
      .insert({
        service_id: input.serviceId,
        customer_id: input.customerId,
        scheduled_on: input.scheduledOn,
        completed_on: input.completedOn,
        kind: input.kind,
        technician: input.technician,
        cost: input.cost,
        summary: input.summary,
      })
      .select(VISIT_COLUMNS)
      .single();

    if (error) {
      throwCrmError(error, "create the maintenance visit");
    }

    return toVisit(data as VisitRow);
  }

  async updateVisit(
    input: UpdateMaintenanceVisitInput,
  ): Promise<MaintenanceVisit> {
    // Only the fields the caller sent are written: `PATCH` keeps the stored value for an omitted one, the
    // same contract `PATCH /api/users/[id]` uses for `branch_id`.
    const patch: {
      scheduled_on?: string;
      completed_on?: string | null;
      kind?: MaintenanceVisitKind;
      technician?: string | null;
      cost?: number;
      summary?: string | null;
    } = {};

    if (input.scheduledOn !== undefined) {
      patch.scheduled_on = input.scheduledOn;
    }

    if (input.completedOn !== undefined) {
      patch.completed_on = input.completedOn;
    }

    if (input.kind !== undefined) {
      patch.kind = input.kind;
    }

    if (input.technician !== undefined) {
      patch.technician = input.technician;
    }

    if (input.cost !== undefined) {
      patch.cost = input.cost;
    }

    if (input.summary !== undefined) {
      patch.summary = input.summary;
    }

    if (Object.keys(patch).length === 0) {
      throw new CrmNotFoundError(
        "Không có thay đổi nào để lưu cho lần bảo trì này.",
      );
    }

    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase
      .from("customer_maintenance_visits")
      .update(patch)
      .eq("id", input.id)
      .select(VISIT_COLUMNS)
      .maybeSingle();

    if (error) {
      throwCrmError(error, "update the maintenance visit");
    }

    if (!data) {
      throw new CrmNotFoundError(
        "Không tìm thấy lần bảo trì này trong tổ chức của bạn.",
      );
    }

    return toVisit(data as VisitRow);
  }

  async removeVisit(id: string): Promise<void> {
    const supabase = await createSupabaseServerClient();
    const { data, error } = await supabase
      .from("customer_maintenance_visits")
      .delete()
      .eq("id", id)
      .select("id")
      .maybeSingle();

    if (error) {
      throwCrmError(error, "delete the maintenance visit");
    }

    if (!data) {
      throw new CrmNotFoundError(
        "Không tìm thấy lần bảo trì này trong tổ chức của bạn.",
      );
    }
  }

}

